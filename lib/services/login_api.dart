import 'package:dio/dio.dart';
import 'package:retrofit/retrofit.dart';
import 'package:pos_app/models/login.dart';

part 'login_api.g.dart';

@RestApi()
abstract class LoginApi { // abstract because we want to define the interface for the API without providing an implementation. The implementation will be generated by Retrofit based on the annotations and method signatures we provide.
  factory LoginApi(Dio dio, {String? baseUrl}) = _LoginApi; // The factory constructor allows us to create an instance of the generated _LoginApi class, which implements the LoginApi interface. We pass in a Dio instance and an optional baseUrl to configure the API client.

  @POST('/api/login')
  Future<LoginResponse> login(@Body() LoginRequest request); // Add the @Body() annotation to indicate that the request body should be sent as JSON and the response should be deserialized into a LoginResponse object
}
